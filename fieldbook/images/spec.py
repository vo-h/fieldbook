"""What an environment image is built from: its tag, Dockerfile, and build context.

fieldbook goes into the image as a wheel of exactly the code on this machine: built from
a source checkout, or packed from the installed files, never installed from PyPI by name
(a package of the same name there could be someone else's).
"""

import base64
import hashlib
import importlib.metadata
import re
import subprocess
import tomllib
import zipfile
from dataclasses import dataclass
from pathlib import Path

import fieldbook
from fieldbook.config import Settings
from fieldbook.launch import LaunchError

GENERATOR = "1"  # bump when the generated Dockerfile changes
UV_IMAGE = "ghcr.io/astral-sh/uv:0.9"
# Large, rarely changing packages get their own layer, so other changes rebuild little.
HEAVY = re.compile(r"^(torch|torchvision|torchaudio|triton|nvidia-.*)$")  # with CUDA libraries
STORAGE_EXTRAS = {"s3": "s3"}


class ImageError(LaunchError):
    pass


class ImageMissing(ImageError):
    """The environment's image is not in the registry yet, and was not to be built."""


@dataclass(frozen=True)
class Environment:
    """What an environment image is built from."""

    repo: Path
    python: str  # major.minor
    base: str
    apt: tuple[str, ...]
    platform: str
    extras: tuple[str, ...]  # requirements for fieldbook on the machine
    lock: str  # uv.lock contents
    pyproject: str
    fieldbook: str  # its version, or "source:<hash>" for a local checkout

    @property
    def tag(self) -> str:
        parts = [GENERATOR, self.python, self.base, *self.apt, self.platform, *self.extras]
        parts += [self.lock, self.pyproject, self.fieldbook]
        return "env-" + hashlib.sha256("\0".join(parts).encode()).hexdigest()[:16]

    def heavy_packages(self) -> list[tuple[str, str, str | None]]:
        """(name, version, index URL or None for PyPI) of the heavy packages in the lock."""
        found = []
        for package in tomllib.loads(self.lock).get("package", []):
            if HEAVY.match(package.get("name", "")) and self._for_this_platform(package):
                registry = package.get("source", {}).get("registry")
                index = None if registry in (None, "https://pypi.org/simple") else registry
                found.append((package["name"], package["version"], index))
        return sorted(found)

    def _for_this_platform(self, package: dict) -> bool:
        """Whether a lock entry is the one for the image's system. A lock holds one entry
        per system when the builds differ (CPU-only torch: `2.9.0` on macOS, `2.9.0+cpu`
        elsewhere), each with the conditions it is for."""
        from packaging.markers import InvalidMarker, Marker

        markers = package.get("resolution-markers")
        if not markers:
            return True
        system, _, machine = self.platform.partition("/")
        machines = {"amd64": "x86_64", "arm64": "aarch64"}
        where = {
            "sys_platform": system,
            "platform_system": system.capitalize(),
            "os_name": "posix",
            "platform_machine": machines.get(machine, machine),
            "python_version": self.python,
            "python_full_version": f"{self.python}.0",
        }
        try:
            return any(Marker(marker).evaluate(where) for marker in markers)
        except InvalidMarker:
            return True


def environment(
    repo: Path, cfg: Settings, python: str, *, platform: str = "linux/amd64"
) -> Environment:
    lock, pyproject = repo / "uv.lock", repo / "pyproject.toml"
    if not lock.is_file() or not pyproject.is_file():
        raise ImageError(
            f"cloud runs need pyproject.toml and uv.lock in {repo}: the environment image is "
            "built from the lock (run `uv lock`)"
        )
    extras = []
    scheme = cfg.storage_root.split("://", 1)[0]
    if scheme in STORAGE_EXTRAS:
        extras.append(f"fieldbook[{STORAGE_EXTRAS[scheme]}]")
    return Environment(
        repo=repo,
        python=".".join(python.split(".")[:2]),
        base=cfg.image_base,
        apt=tuple(sorted(cfg.image_apt)),
        platform=platform,
        extras=tuple(extras),
        lock=lock.read_text(),
        pyproject=pyproject.read_text(),
        fieldbook=_fieldbook_version(),
    )


def dockerfile(env: Environment, wheel: str) -> str:
    """The generated Dockerfile. `wheel` is fieldbook's wheel in the build context."""
    apt = " ".join(["ca-certificates", *env.apt])
    lines = [
        f"# Generated by fieldbook build: environment {env.tag} (cloud-runs.md §5).",
        "# Code is not in the image; each run checks out its snapshot.",
        f"FROM {env.base}",
        "RUN apt-get update && apt-get install -y --no-install-recommends "
        f"{apt} && rm -rf /var/lib/apt/lists/*",
        f"COPY --from={UV_IMAGE} /uv /usr/local/bin/uv",
        "ENV UV_PYTHON_INSTALL_DIR=/opt/python UV_PROJECT_ENVIRONMENT=/opt/venv "
        "VIRTUAL_ENV=/opt/venv PATH=/opt/venv/bin:$PATH UV_LINK_MODE=copy",
        f"RUN uv venv /opt/venv --python {env.python}",
    ]
    heavy = env.heavy_packages()
    if heavy:
        lines.append("# Heavy packages, at the versions in uv.lock")
        for index in sorted({i for _, _, i in heavy}, key=str):
            pins = " ".join(f"{n}=={v}" for n, v, i in heavy if i == index)
            # The package's own index first, PyPI for what it depends on. (uv looks in an
            # --extra-index-url before the --index-url, so that pair found PyPI's torch
            # and no `+cpu` build.)
            source = f" --index {index} --default-index https://pypi.org/simple" if index else ""
            lines.append(f"RUN uv pip install --python /opt/venv{source} {pins}")
    lines += [
        "# Everything else in uv.lock",
        "WORKDIR /opt/env",
        "COPY pyproject.toml uv.lock ./",
        "RUN uv sync --frozen --no-install-project --no-install-package fieldbook",
        "# fieldbook itself, with what the platform needs on the machine",
    ]
    lines.append(f"COPY {wheel} ./")
    target = f"./{wheel}"
    extras = sorted({e.split("[", 1)[1].rstrip("]") for e in env.extras})
    spec = f"{target}[{','.join(extras)}]" if extras else target
    lines.append(f'RUN uv pip install --python /opt/venv "{spec}" "psycopg[binary]"')
    lines.append("WORKDIR /root")
    return "\n".join(lines) + "\n"


def build_context(env: Environment, directory: Path) -> Path:
    """Write the build context (Dockerfile, pyproject.toml, uv.lock, and fieldbook's wheel)
    to `directory`."""
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "pyproject.toml").write_text(env.pyproject)
    (directory / "uv.lock").write_text(env.lock)
    source = _fieldbook_source()
    if source is None:
        wheel = pack_installed(importlib.metadata.distribution("fieldbook"), directory)
    else:
        result = subprocess.run(
            ["uv", "build", "--wheel", "--out-dir", str(directory), str(source)],
            capture_output=True, text=True,
        )  # fmt: skip
        if result.returncode != 0:
            raise ImageError(f"could not build fieldbook's wheel: {result.stderr.strip()[-300:]}")
        wheel = next(directory.glob("fieldbook-*.whl")).name
    (directory / "Dockerfile").write_text(dockerfile(env, wheel))
    return directory


INSTALL_RECORDS = {"INSTALLER", "REQUESTED", "direct_url.json", "RECORD"}  # this install only


def pack_installed(dist: importlib.metadata.Distribution, directory: Path) -> str:
    """Pack an installed distribution's own files (its package and metadata, not compiled
    files or scripts) into a wheel in `directory`; returns the wheel's file name."""
    name = dist.metadata["Name"].replace("-", "_")
    wheel = f"{name}-{dist.version}-py3-none-any.whl"
    info = f"{name}-{dist.version}.dist-info"
    record = []
    with zipfile.ZipFile(directory / wheel, "w", zipfile.ZIP_DEFLATED) as zf:
        for file in sorted(dist.files or [], key=str):
            parts = file.parts
            if parts[0] == ".." or "__pycache__" in parts or file.suffix == ".pyc":
                continue  # scripts outside site-packages, compiled files
            if parts[0] == info and parts[-1] in INSTALL_RECORDS:
                continue
            data = Path(file.locate()).read_bytes()
            zf.writestr(file.as_posix(), data)
            digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=")
            record.append(f"{file.as_posix()},sha256={digest.decode()},{len(data)}")
        record.append(f"{info}/RECORD,,")
        zf.writestr(f"{info}/RECORD", "\n".join(record) + "\n")
    return wheel


def _fieldbook_source() -> Path | None:
    """fieldbook's source tree if it is installed from a local checkout, else None."""
    root = Path(fieldbook.__file__).resolve().parents[1]
    pyproject = root / "pyproject.toml"
    if pyproject.is_file() and 'name = "fieldbook"' in pyproject.read_text():
        return root
    return None


def _fieldbook_version() -> str:
    source = _fieldbook_source()
    if source is None:
        return fieldbook.__version__
    digest = hashlib.sha256()
    for path in sorted((source / "fieldbook").rglob("*.py")) + [source / "pyproject.toml"]:
        digest.update(str(path.relative_to(source)).encode() + b"\0" + path.read_bytes())
    return "source:" + digest.hexdigest()[:16]
